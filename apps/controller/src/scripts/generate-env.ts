/**
 * Generates a local .env with fresh secrets (Ed25519 signing key, JWT secret,
 * webhook secret). Safe to re-run; it never overwrites an existing .env.
 */
import { existsSync, writeFileSync, readFileSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import { generateEd25519Keypair } from '@strict-proxy/types';

const ENV_PATH = new URL('../../../../.env', import.meta.url).pathname;

if (existsSync(ENV_PATH)) {
  console.log('[env] .env already exists; leaving it untouched.');
  process.exit(0);
}

const kp = generateEd25519Keypair();
const env = `# Generated by strict-proxy dev tooling
PORT=8080
DATABASE_URL=postgres://strict:strict@localhost:5432/strict_proxy
REDIS_URL=redis://localhost:6379
JWT_SECRET=${randomBytes(48).toString('base64url')}
SIGNING_PRIVATE_KEY_PEM="${kp.privateKeyPem.replace(/\n/g, '\\n')}"
SIGNING_KEY_ID=primary
PAYMENT_WEBHOOK_SECRET=${randomBytes(32).toString('hex')}
CORS_ORIGINS=*
SEED_ADMIN_EMAIL=admin@strict.local
SEED_ADMIN_PASSWORD=${randomBytes(9).toString('base64url')}
`;

writeFileSync(ENV_PATH, env, 'utf8');
console.log('[env] wrote .env with fresh secrets.');
console.log('[env] Ed25519 PUBLIC key (share with Gatekeeper SDK / client verification):');
console.log(kp.publicKeyPem);
console.log('[env] admin password:', readFileSync(ENV_PATH, 'utf8').match(/SEED_ADMIN_PASSWORD=(.+)/)?.[1] ?? '(see .env)');
